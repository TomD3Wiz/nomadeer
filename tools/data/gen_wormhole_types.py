#!/usr/bin/env python3
"""Regenerate the wormhole type table in src/data/wormhole_types.rs.

Everything comes from ESI's public endpoints. The "Wormhole" group is found by
name under the "Celestial" category, then every type in it is read with its dogma
attributes, whose IDs are resolved by name through /dogma/attributes so a
renumbering on CCP's side cannot silently shift columns.

ESI marks every wormhole type unpublished (none of them can be owned), so the
`published` flag cannot pick out real holes. The name does instead: "Wormhole
B274" is kept, test entries such as "QA Wormhole A" are dropped and reported.

Units, checked by the attribute's unit_id where ESI gives one:
  wormholeMaxStableTime     unit_id 3 claims seconds, but the values are minutes
                            (the C1 static Z971 reads 960, i.e. its 16 hours).
  wormholeMaxStableMass     kg (unit_id 2)
  wormholeMaxJumpMass       kg (unit_id 2)
  wormholeMassRegeneration  kg restored per regeneration cycle (unit_id 2)
  wormholeTargetSystemClass a class number, mapped through TARGET_CLASSES below.

Types sharing a code (the C729 Pochven variants, a reissued J244) must agree on
every stat; they are folded into one entry that lists the extra type IDs.

Usage:
    python3 tools/data/gen_wormhole_types.py

Only the lines between the BEGIN/END GENERATED markers are replaced; the types and
lookups around them are maintained by hand. A class number the table does not know
stops the run, so add it to both TARGET_CLASSES below and the Rust enum.
"""

import argparse
import concurrent.futures
import json
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request

ESI = "https://esi.evetech.net/latest"
CATEGORY = "Celestial"
GROUP = "Wormhole"
CODE = re.compile(r"^Wormhole ([A-Z]\d{3})$")
EXIT_CODE = "K162"

ATTRIBUTES = {
    "target": ("wormholeTargetSystemClass", None),
    "minutes": ("wormholeMaxStableTime", 3),
    "total": ("wormholeMaxStableMass", 2),
    "regen": ("wormholeMassRegeneration", 2),
    "jump": ("wormholeMaxJumpMass", 2),
}

# wormholeTargetSystemClass -> `TargetClass` variant in src/data/wormhole_types.rs.
TARGET_CLASSES = {
    -1: "Varies",
    1: "C1",
    2: "C2",
    3: "C3",
    4: "C4",
    5: "C5",
    6: "C6",
    7: "HighSec",
    8: "LowSec",
    9: "NullSec",
    12: "Thera",
    13: "C13",
    14: "C14",
    15: "C15",
    16: "C16",
    17: "C17",
    18: "C18",
    25: "Pochven",
}

BEGIN = "// BEGIN GENERATED by tools/data/gen_wormhole_types.py"
END = "// END GENERATED"


def get(path):
    """GETs an ESI path as JSON, retrying the transient errors ESI is known for."""
    request = urllib.request.Request(
        f"{ESI}{path}", headers={"User-Agent": "Nomadeer data generator"}
    )
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            if error.code < 500 and error.code != 420:
                raise
        except urllib.error.URLError:
            pass
        time.sleep(2**attempt)
    sys.exit(f"ESI kept failing on {path}")


def get_all(paths):
    with concurrent.futures.ThreadPoolExecutor(max_workers=16) as pool:
        return list(pool.map(get, paths))


def find_group():
    categories = get_all(f"/universe/categories/{id}/" for id in get("/universe/categories/"))
    category = next((c for c in categories if c["name"] == CATEGORY), None)
    if category is None:
        sys.exit(f'no "{CATEGORY}" category in ESI')
    groups = get_all(f"/universe/groups/{id}/" for id in category["groups"])
    matches = [g for g in groups if g["name"] == GROUP]
    if len(matches) != 1:
        sys.exit(f'expected one "{GROUP}" group, found {[g["group_id"] for g in matches]}')
    return matches[0]


def resolve_attributes(types):
    ids = sorted({a["attribute_id"] for t in types for a in t.get("dogma_attributes", [])})
    by_name = {a["name"]: a for a in get_all(f"/dogma/attributes/{id}/" for id in ids)}
    resolved = {}
    for key, (name, unit) in ATTRIBUTES.items():
        attribute = by_name.get(name)
        if attribute is None:
            sys.exit(f"no wormhole type carries {name}")
        if attribute.get("unit_id") != unit:
            sys.exit(f"{name} now has unit_id {attribute.get('unit_id')}, expected {unit}")
        resolved[key] = attribute["attribute_id"]
    return resolved


def read_type(t, attributes):
    """The code and stats of one wormhole type, or None for K162."""
    code = CODE.match(t["name"]).group(1)
    values = {a["attribute_id"]: a["value"] for a in t.get("dogma_attributes", [])}
    if code == EXIT_CODE:
        if any(id in values for id in attributes.values()):
            sys.exit("K162 now carries wormhole stats; the generic exit entry needs a rethink")
        return code, None
    missing = [key for key, id in attributes.items() if id not in values]
    if missing:
        sys.exit(f"{t['name']} ({t['type_id']}) lacks {missing}")
    target = int(values[attributes["target"]])
    if target not in TARGET_CLASSES:
        sys.exit(f"{t['name']} leads to class {target}, which has no TargetClass variant yet")
    minutes = values[attributes["minutes"]]
    if minutes % 30 or not 60 <= minutes <= 2880:
        sys.exit(f"{t['name']} lives {minutes} minutes; check the time unit")
    stats = (
        TARGET_CLASSES[target],
        minutes / 60,
        int(values[attributes["total"]]),
        int(values[attributes["jump"]]),
        int(values[attributes["regen"]]),
    )
    return code, stats


def render(entries, note):
    lines = [
        BEGIN,
        f"// {note}",
        "",
        "/// Code, type ID, target, max stable hours, total mass, max jump mass and mass",
        "/// regeneration (kg); `also` lists further type IDs sharing the code.",
        "#[rustfmt::skip]",
        "pub(crate) static WORMHOLE_TYPES: &[WormholeType] = &[",
    ]
    for code, ids, stats in entries:
        if stats is None:
            lines.append(f'    exit("{code}", {ids[0]}),')
            continue
        target, hours, total, jump, regen = stats
        line = f'    wormhole("{code}", {ids[0]}, {target}, {hours:.1f}, {total:_}, {jump:_}, {regen:_})'
        if len(ids) > 1:
            line += f".also(&[{', '.join(map(str, ids[1:]))}])"
        lines.append(line + ",")
    lines += ["];", END]
    return "\n".join(lines)


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=pathlib.Path, default=root / "src/data/wormhole_types.rs")
    args = parser.parse_args()

    group = find_group()
    types = get_all(f"/universe/types/{id}/" for id in sorted(group["types"]))
    kept = [t for t in types if CODE.match(t["name"])]
    for t in types:
        if not CODE.match(t["name"]):
            print(f"skipping {t['name']} ({t['type_id']})", file=sys.stderr)
    attributes = resolve_attributes(kept)

    by_code = {}
    for t in kept:
        code, stats = read_type(t, attributes)
        if code in by_code:
            ids, known = by_code[code]
            if known != stats:
                sys.exit(f"{code} types {ids + [t['type_id']]} disagree: {known} vs {stats}")
            ids.append(t["type_id"])
        else:
            by_code[code] = ([t["type_id"]], stats)
    if EXIT_CODE not in by_code:
        sys.exit("ESI no longer lists K162")

    entries = sorted(
        ((code, ids, stats) for code, (ids, stats) in by_code.items()), key=lambda e: e[1][0]
    )
    note = (
        f"{len(entries)} codes from {len(kept)} types in ESI group {group['group_id']} "
        f'"{GROUP}".'
    )
    block = render(entries, note)

    text = args.out.read_text(encoding="utf-8")
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        sys.exit(f"{args.out} has no generated block to replace")
    args.out.write_text(text[:start] + block + text[end + len(END) :], encoding="utf-8")
    print(f"group {group['group_id']}: {len(types)} types -> {len(entries)} wormhole codes")


if __name__ == "__main__":
    main()
