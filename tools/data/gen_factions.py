#!/usr/bin/env python3
"""Regenerate the k-space faction tables in src/data/factions.rs.

The owning NPC faction of every known-space system comes from CCP's Static Data
Export as mirrored by Fuzzwork (mapSolarSystems.csv carries a factionID per
system). The tables are compressed to one faction per region, with constellation
and system overrides wherever the systems below disagree, and the result is
checked against every system before the generated block is rewritten.

Usage:
    python3 tools/data/gen_factions.py                 # download the latest SDE CSVs
    python3 tools/data/gen_factions.py --sde-dir DIR   # use CSVs already on disk

Only the lines between the BEGIN/END GENERATED markers are replaced; the enum and
lookup code around them are maintained by hand. A faction the enum does not know
stops the run, so add its variant to both FACTIONS below and the Rust enum.
"""

import argparse
import csv
import email.utils
import pathlib
import sys
import tempfile
import urllib.request
from collections import Counter, defaultdict

FUZZWORK_CSV = "https://www.fuzzwork.co.uk/dump/latest/csv/"
SDE_FILES = ("mapSolarSystems", "mapRegions", "mapConstellations", "chrFactions")
KSPACE = range(30_000_000, 31_000_000)

# SDE factionID -> `Faction` variant in src/data/factions.rs.
FACTIONS = {
    500001: "CaldariState",
    500002: "MinmatarRepublic",
    500003: "AmarrEmpire",
    500004: "GallenteFederation",
    500005: "JoveEmpire",
    500006: "Concord",
    500007: "AmmatarMandate",
    500008: "KhanidKingdom",
    500010: "GuristasPirates",
    500011: "AngelCartel",
    500012: "BloodRaiderCovenant",
    500013: "EverMore",
    500014: "Ore",
    500015: "ThukkerTribe",
    500016: "SistersOfEve",
    500017: "SocietyOfConsciousThought",
    500018: "MordusLegion",
    500019: "SanshasNation",
    500020: "Serpentis",
    500026: "TriglavianCollective",
    500029: "DeathlessCircle",
}

BEGIN = "// BEGIN GENERATED by tools/data/gen_factions.py"
END = "// END GENERATED"


def download(directory):
    """Fetches the SDE CSVs into `directory` and returns the export's date."""
    modified = None
    for name in SDE_FILES:
        request = urllib.request.Request(
            f"{FUZZWORK_CSV}{name}.csv", headers={"User-Agent": "Nomadeer data generator"}
        )
        with urllib.request.urlopen(request, timeout=60) as response:
            (directory / f"{name}.csv").write_bytes(response.read())
            header = response.headers.get("Last-Modified")
            if name == "mapSolarSystems" and header:
                modified = email.utils.parsedate_to_datetime(header).date().isoformat()
    return modified


def read_csv(directory, name):
    with open(directory / f"{name}.csv", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def faction_of(raw, names, system):
    if not raw:
        return None
    faction_id = int(raw)
    if faction_id not in FACTIONS:
        sys.exit(
            f"{system} belongs to faction {faction_id} ({names.get(faction_id, '?')}), "
            "which has no Faction variant yet"
        )
    return faction_id


def majority(counter, preferred):
    """The most common faction, keeping `preferred` on a tie so fewer overrides appear."""
    best = max(counter.values())
    tied = [faction for faction, count in counter.items() if count == best]
    if preferred in tied:
        return preferred
    return min(tied, key=lambda faction: -1 if faction is None else faction)


def compress(systems):
    """Region defaults plus constellation and system overrides for `systems`.

    `systems` maps system ID -> (region ID, constellation ID, faction ID or None).
    """
    by_region = defaultdict(Counter)
    by_constellation = defaultdict(Counter)
    for region, constellation, faction in systems.values():
        by_region[region][faction] += 1
        by_constellation[(region, constellation)][faction] += 1

    regions = {region: majority(counts, None) for region, counts in by_region.items()}
    constellation_defaults = {
        key: majority(counts, regions[key[0]]) for key, counts in by_constellation.items()
    }
    constellations = {
        constellation: faction
        for (region, constellation), faction in constellation_defaults.items()
        if faction != regions[region]
    }
    overrides = {
        system: faction
        for system, (region, constellation, faction) in systems.items()
        if faction != constellation_defaults[(region, constellation)]
    }
    return regions, constellations, overrides


def lookup(regions, constellations, overrides, system, region, constellation):
    """Mirrors `faction_for_system` in Rust, so the tables can be checked here."""
    if system in overrides:
        return overrides[system]
    if constellation in constellations:
        return constellations[constellation]
    return regions.get(region)


def rust_option(faction):
    return "None" if faction is None else f"Some({FACTIONS[faction]})"


def table_rows(entries):
    """`(id, value), // name` lines with the comments aligned as rustfmt leaves them."""
    width = max(len(code) for code, _ in entries)
    return [f"    {code.ljust(width)} // {comment}" for code, comment in entries]


def render(regions, constellations, overrides, comments, source_note):
    lines = [
        BEGIN,
        f"// {source_note}",
        "",
        "/// Regions whose systems mostly belong to one faction. Regions not listed are",
        "/// mostly unclaimed by NPCs.",
        "const REGION_FACTIONS: &[(u32, Faction)] = &[",
    ]
    lines += table_rows(
        [
            (f"({region}, {FACTIONS[faction]}),", comments[region])
            for region, faction in sorted(regions.items())
            if faction is not None
        ]
    )
    lines += [
        "];",
        "",
        "/// Constellations that differ from their region.",
        "const CONSTELLATION_FACTIONS: &[(u32, Option<Faction>)] = &[",
    ]
    lines += table_rows(
        [
            (f"({constellation}, {rust_option(faction)}),", comments[constellation])
            for constellation, faction in sorted(constellations.items())
        ]
    )
    lines += [
        "];",
        "",
        "/// Systems that differ from their constellation.",
        "const SYSTEM_FACTIONS: &[(u32, Option<Faction>)] = &[",
    ]
    lines += table_rows(
        [
            (f"({system}, {rust_option(faction)}),", comments[system])
            for system, faction in sorted(overrides.items())
        ]
    )
    lines += ["];", END]
    return "\n".join(lines)


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sde-dir", type=pathlib.Path, help="directory holding the SDE CSVs")
    parser.add_argument("--out", type=pathlib.Path, default=root / "src/data/factions.rs")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as scratch:
        if args.sde_dir:
            directory, modified = args.sde_dir, None
        else:
            directory = pathlib.Path(scratch)
            modified = download(directory)
        names = {int(row["factionID"]): row["factionName"] for row in read_csv(directory, "chrFactions")}
        region_names = {int(row["regionID"]): row["regionName"] for row in read_csv(directory, "mapRegions")}
        constellation_names = {
            int(row["constellationID"]): row["constellationName"]
            for row in read_csv(directory, "mapConstellations")
        }
        systems = {}
        system_names = {}
        for row in read_csv(directory, "mapSolarSystems"):
            system = int(row["solarSystemID"])
            if system not in KSPACE:
                continue
            name = row["solarSystemName"]
            systems[system] = (
                int(row["regionID"]),
                int(row["constellationID"]),
                faction_of(row["factionID"], names, name),
            )
            system_names[system] = name

    regions, constellations, overrides = compress(systems)
    for system, (region, constellation, faction) in systems.items():
        found = lookup(regions, constellations, overrides, system, region, constellation)
        if found != faction:
            sys.exit(f"compressed tables give {found} for {system_names[system]}, not {faction}")

    comments = {**region_names, **constellation_names, **system_names}
    source = "Fuzzwork's SDE mirror" + (f" of {modified}" if modified else "")
    note = f"{len(systems)} k-space systems from {source}."
    block = render(regions, constellations, overrides, comments, note)

    text = args.out.read_text(encoding="utf-8")
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        sys.exit(f"{args.out} has no generated block to replace")
    args.out.write_text(text[:start] + block + text[end + len(END) :], encoding="utf-8")
    print(
        f"{len(systems)} systems -> {sum(f is not None for f in regions.values())} regions, "
        f"{len(constellations)} constellations, {len(overrides)} systems"
    )


if __name__ == "__main__":
    main()
