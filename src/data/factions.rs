#[cfg(test)]
mod tests {
    use super::{
        CONSTELLATION_FACTIONS, EmpireGroup, Faction, REGION_FACTIONS, SYSTEM_FACTIONS,
        empire_group, faction_for_system,
    };

    #[test]
    fn empire_hubs_belong_to_their_empires() {
        // Perimeter and New Caldari, beside Jita.
        assert_eq!(
            faction_for_system(30000144, 10000002, 20000020),
            Some(Faction::CaldariState)
        );
        assert_eq!(
            faction_for_system(30000145, 10000002, 20000020),
            Some(Faction::CaldariState)
        );
        assert_eq!(
            faction_for_system(30002187, 10000043, 20000322),
            Some(Faction::AmarrEmpire)
        );
        assert_eq!(
            faction_for_system(30002659, 10000032, 20000389),
            Some(Faction::GallenteFederation)
        );
        assert_eq!(
            faction_for_system(30002510, 10000030, 20000367),
            Some(Faction::MinmatarRepublic)
        );
    }

    #[test]
    fn concord_holds_jita_and_yulai() {
        // The SDE and ESI's sovereignty map both give Jita to CONCORD, not the State.
        assert_eq!(
            faction_for_system(30000142, 10000002, 20000020),
            Some(Faction::Concord)
        );
        assert_eq!(
            faction_for_system(30005204, 10000067, 20000761),
            Some(Faction::Concord)
        );
        assert_eq!(
            faction_for_system(30005203, 10000067, 20000761),
            Some(Faction::EverMore)
        );
    }

    #[test]
    fn pochven_npc_null_and_sov_null() {
        // Otela, a Pochven system still numbered among The Forge's.
        assert_eq!(
            faction_for_system(30000157, 10000070, 20000787),
            Some(Faction::TriglavianCollective)
        );
        // 6NJ8-V in Venal is NPC null-sec.
        assert_eq!(
            faction_for_system(30001290, 10000015, 20000188),
            Some(Faction::GuristasPirates)
        );
        // 1DQ1-A in Delve is player-held.
        assert_eq!(faction_for_system(30004759, 10000060, 20000696), None);
        // Zarzakh sits alone in its region.
        assert_eq!(
            faction_for_system(30100000, 10001000, 20010000),
            Some(Faction::DeathlessCircle)
        );
    }

    #[test]
    fn wormholes_and_unknown_ids_have_no_faction() {
        assert_eq!(faction_for_system(31000005, 11000001, 21000001), None);
        assert_eq!(faction_for_system(0, 0, 0), None);
        assert_eq!(faction_for_system(30000144, u64::MAX, u64::MAX), None);
    }

    #[test]
    fn tables_are_sorted_for_binary_search() {
        fn strictly_ascending<T>(table: &[(u32, T)]) -> bool {
            table.windows(2).all(|pair| pair[0].0 < pair[1].0)
        }
        assert!(strictly_ascending(REGION_FACTIONS));
        assert!(strictly_ascending(CONSTELLATION_FACTIONS));
        assert!(strictly_ascending(SYSTEM_FACTIONS));
    }

    #[test]
    fn empire_groups_fold_in_allied_factions() {
        assert_eq!(
            empire_group(Some(Faction::KhanidKingdom)),
            EmpireGroup::Amarr
        );
        assert_eq!(
            empire_group(Some(Faction::AmmatarMandate)),
            EmpireGroup::Amarr
        );
        assert_eq!(
            empire_group(Some(Faction::ThukkerTribe)),
            EmpireGroup::Minmatar
        );
        assert_eq!(
            empire_group(Some(Faction::SanshasNation)),
            EmpireGroup::Pirate
        );
        assert_eq!(empire_group(Some(Faction::Ore)), EmpireGroup::Other);
        assert_eq!(empire_group(None), EmpireGroup::Other);
    }
}
