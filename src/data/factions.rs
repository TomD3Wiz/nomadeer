//! The NPC faction that owns each known-space system, for colouring the chain map's
//! k-space systems. The tables are generated from CCP's Static Data Export by
//! tools/data/gen_factions.py; rerun it after a map change rather than editing them.

/// Known-space solar system IDs. Wormhole, abyssal and other instanced space
/// lies outside this range and belongs to no faction.
const KSPACE_SYSTEMS: std::ops::RangeInclusive<u64> = 30_000_000..=30_999_999;

/// An NPC faction that holds sovereignty over known space.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) enum Faction {
    AmarrEmpire,
    CaldariState,
    GallenteFederation,
    MinmatarRepublic,
    AmmatarMandate,
    KhanidKingdom,
    JoveEmpire,
    Concord,
    EverMore,
    SanshasNation,
    GuristasPirates,
    Serpentis,
    AngelCartel,
    BloodRaiderCovenant,
    DeathlessCircle,
    Ore,
    ThukkerTribe,
    MordusLegion,
    SistersOfEve,
    SocietyOfConsciousThought,
    TriglavianCollective,
}

/// Broad allegiance used to pick a colour for a faction's space.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) enum EmpireGroup {
    /// The Amarr Empire with the Ammatar Mandate and the Khanid Kingdom.
    Amarr,
    Caldari,
    Gallente,
    /// The Minmatar Republic with the Thukker Tribe.
    Minmatar,
    Pirate,
    /// Neutral and outside powers, and space no NPC faction holds.
    Other,
}

impl Faction {
    pub(crate) fn display_name(self) -> &'static str {
        match self {
            Self::AmarrEmpire => "Amarr Empire",
            Self::CaldariState => "Caldari State",
            Self::GallenteFederation => "Gallente Federation",
            Self::MinmatarRepublic => "Minmatar Republic",
            Self::AmmatarMandate => "Ammatar Mandate",
            Self::KhanidKingdom => "Khanid Kingdom",
            Self::JoveEmpire => "Jove Empire",
            Self::Concord => "CONCORD Assembly",
            Self::EverMore => "EverMore",
            Self::SanshasNation => "Sansha's Nation",
            Self::GuristasPirates => "Guristas Pirates",
            Self::Serpentis => "Serpentis",
            Self::AngelCartel => "Angel Cartel",
            Self::BloodRaiderCovenant => "Blood Raider Covenant",
            Self::DeathlessCircle => "Deathless Circle",
            Self::Ore => "ORE",
            Self::ThukkerTribe => "Thukker Tribe",
            Self::MordusLegion => "Mordu's Legion",
            Self::SistersOfEve => "Sisters of EVE",
            Self::SocietyOfConsciousThought => "Society of Conscious Thought",
            Self::TriglavianCollective => "Triglavian Collective",
        }
    }

    pub(crate) fn empire_group(self) -> EmpireGroup {
        match self {
            Self::AmarrEmpire | Self::AmmatarMandate | Self::KhanidKingdom => EmpireGroup::Amarr,
            Self::CaldariState => EmpireGroup::Caldari,
            Self::GallenteFederation => EmpireGroup::Gallente,
            Self::MinmatarRepublic | Self::ThukkerTribe => EmpireGroup::Minmatar,
            Self::SanshasNation
            | Self::GuristasPirates
            | Self::Serpentis
            | Self::AngelCartel
            | Self::BloodRaiderCovenant
            | Self::DeathlessCircle => EmpireGroup::Pirate,
            Self::JoveEmpire
            | Self::Concord
            | Self::EverMore
            | Self::Ore
            | Self::MordusLegion
            | Self::SistersOfEve
            | Self::SocietyOfConsciousThought
            | Self::TriglavianCollective => EmpireGroup::Other,
        }
    }
}

/// The colour grouping for a system's owner; unclaimed space counts as `Other`.
// The chain map gives unclaimed space no badge, so nothing asks yet.
#[allow(dead_code)]
pub(crate) fn empire_group(faction: Option<Faction>) -> EmpireGroup {
    faction.map_or(EmpireGroup::Other, Faction::empire_group)
}

/// The NPC faction holding a known-space system, or `None` for player-held and
/// unclaimed null-sec and for anything outside known space.
pub(crate) fn faction_for_system(
    solar_system_id: u64,
    region_id: u64,
    constellation_id: u64,
) -> Option<Faction> {
    if !KSPACE_SYSTEMS.contains(&solar_system_id) {
        return None;
    }
    if let Some(faction) = find(SYSTEM_FACTIONS, solar_system_id) {
        return faction;
    }
    if let Some(faction) = find(CONSTELLATION_FACTIONS, constellation_id) {
        return faction;
    }
    find(REGION_FACTIONS, region_id)
}

fn find<T: Copy>(table: &[(u32, T)], id: u64) -> Option<T> {
    let id = u32::try_from(id).ok()?;
    table
        .binary_search_by_key(&id, |&(key, _)| key)
        .ok()
        .map(|index| table[index].1)
}

